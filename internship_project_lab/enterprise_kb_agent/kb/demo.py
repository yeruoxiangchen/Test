def seed(db, settings):
    base = db.one("SELECT * FROM bases WHERE name='团队示例资料'")
    if not base:
        base_id = uid()
        db.execute("INSERT INTO bases VALUES(?,?,?,?,?)", (base_id, "团队示例资料", "虚构资料，用于体验文档检索与问答", "all", time.time()))
    else:
        base_id = base["id"]
    ids = []
    for name, content in DOCUMENTS.items():
        doc, _ = register_document(db, settings, base_id, name, content.encode())
        ingest(db, settings, doc["id"])
        ids.append(doc["id"])
    return base_id, ids
