import { chromium } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { openSync, closeSync } from 'node:fs';

const base = 'http://127.0.0.1:18802';
const directory = path.join(process.env.AIGC_DATA_ROOT, 'checks', 'ui');
await mkdir(directory, { recursive: true });
const log = openSync(path.join(directory, 'server.log'), 'w');
const server = spawn(path.join(process.env.AIGC_DATA_ROOT, 'venv/bin/python'), ['-B', '-m', 'uvicorn', 'tests.preview:factory', '--factory', '--host', '127.0.0.1', '--port', '18802'], {cwd: fileURLToPath(new URL('../', import.meta.url)), stdio: ['ignore', log, log]});
closeSync(log);
let browser;
const errors = [];
try {
  let connected = false;
  for (let i = 0; i < 60; i++) {
    if (server.exitCode !== null) throw new Error('Browser test server exited; see checks/ui/server.log');
    try {connected = (await fetch(base + '/api/health')).ok;} catch {}
    if (connected) break;
    await new Promise(resolve => setTimeout(resolve, 500));
  }
  assert.ok(connected, 'Browser test server did not start');
  browser = await chromium.launch({ channel: 'chromium', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base, { waitUntil: 'networkidle' });
  await page.evaluate(() => document.fonts.ready);
  await page.getByRole('heading', { name: '把灵感，变成作品。' }).waitFor();
  await page.screenshot({ path: path.join(directory, 'desktop.png'), fullPage: true });
  await page.getByLabel('画面描述').fill('browser queue fixture');
  await page.getByRole('button', { name: '加入生成队列', exact: true }).click();
  await page.getByRole('heading', { name: '灵感已就位' }).waitFor();
  let jobs = await (await page.request.get(base + '/api/jobs')).json();
  assert.equal(jobs.items.length, 1);
  const first = jobs.items[0].id;
  await page.reload();
  await page.getByRole('heading', { name: '灵感已就位' }).waitFor();
  await page.getByRole('button', { name: '取消任务', exact: true }).click();
  await page.getByRole('heading', { name: '随时开始下一次创作' }).waitFor();
  await page.getByLabel('画面描述').fill('browser gallery fixture');
  await page.getByRole('button', { name: '加入生成队列', exact: true }).click();
  await page.getByRole('heading', { name: '灵感已就位' }).waitFor();
  jobs = await (await page.request.get(base + '/api/jobs')).json();
  assert.equal(jobs.items.length, 2);
  assert.notEqual(first, jobs.items[0].id);
  assert.equal((await page.request.post(base + '/api/test-fixture/' + jobs.items[0].id)).status(), 200);
  await page.getByRole('link', { name: '下载作品', exact: true }).waitFor();
  const download = page.waitForEvent('download');
  await page.getByRole('link', { name: '下载作品', exact: true }).click();
  assert.match((await download).suggestedFilename(), /\.png$/);
  await page.getByRole('button', { name: '放大作品' }).click();
  await page.getByRole('dialog').waitFor();
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: /^作品库/ }).click();
  await page.getByRole('button', { name: '查看作品 browser gallery fixture' }).waitFor();
  await page.getByRole('button', { name: '开始创作', exact: true }).click();
  await page.getByRole('tab', { name: '视频', exact: true }).click();
  await page.getByLabel('视频长度').selectOption('33');
  await page.getByRole('tab', { name: '图片转视频', exact: true }).click();
  const asset = await page.request.get(base + '/api/assets/' + (await (await page.request.get(base + '/api/jobs')).json()).items[0].outputs[0]);
  await page.locator('input[type=file]').setInputFiles({ name: 'reference.png', mimeType: 'image/png', buffer: await asset.body() });
  await page.getByAltText('参考图片').waitFor();
  await page.getByRole('button', { name: '加入生成队列', exact: true }).click();
  await page.getByRole('heading', { name: '灵感已就位' }).waitFor();
  jobs = await (await page.request.get(base + '/api/jobs')).json();
  assert.equal(jobs.items[0].params.mode, 'image-to-video');
  assert.ok(jobs.items[0].params.input_asset_id);
  await page.getByRole('button', { name: '生成资源', exact: true }).click();
  await page.getByRole('heading', { name: '创作背后的算力。' }).waitFor();
  await page.screenshot({ path: path.join(directory, 'resources.png'), fullPage: true });
  await page.getByRole('button', { name: '创作工作台', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: path.join(directory, 'mobile.png'), fullPage: true });
  const overflow = await page.evaluate(() => ({width: window.innerWidth, scroll: document.documentElement.scrollWidth, elements: [...document.querySelectorAll('body *')].filter(e => e.getBoundingClientRect().right > window.innerWidth + 1).map(e => ({tag: e.tagName, class: e.className, right: e.getBoundingClientRect().right})).slice(0, 15)}));
  await writeFile(path.join(directory, 'mobile-layout.json'), JSON.stringify(overflow, null, 2));
  assert.ok(overflow.scroll <= overflow.width, 'Mobile view must not overflow horizontally: ' + JSON.stringify(overflow));
  assert.deepEqual(errors, []);
  const report = { passed: true, checks: ['desktop', 'queue', 'persistence', 'cancel', 'asset download', 'gallery', 'modal', 'image upload', 'image-to-video', 'resources', 'mobile overflow'], browserErrors: errors };
  await writeFile(path.join(directory, 'report.json'), JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report));
} finally {
  await browser?.close();
  server.kill('SIGTERM');
  await new Promise(resolve => {server.once('exit', resolve); setTimeout(resolve, 3000).unref();});
  if (server.exitCode === null) server.kill('SIGKILL');
}
